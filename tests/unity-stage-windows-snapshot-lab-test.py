#!/usr/bin/env python3
"""C5g scratch-copy integrity tests; no real Unity stage or authority paths."""
import importlib.util
from pathlib import Path
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "c5g_scratch_snapshot", ROOT / "scripts/unity-stage-windows-snapshot-lab.py")
lab = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(lab)


class ScratchSnapshotTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.home = Path(temp.name)
        self.stage = self.home / "fake-stage"
        self.stage.mkdir()
        for name in lab.ROOTS:
            (self.stage / name).mkdir()
        self.original = "Assets/Scenes/PlaytestScene.unity"
        self.proof = "Assets/Generated/Proof.unity"
        lab.write_asset(self.stage, self.original, "original bytes\n")
        lab.write_asset(self.stage, self.proof, "generated bytes\n")
        lab.write_asset(self.stage, self.proof + ".meta", "guid: " + "a" * 32 + "\n")
        lab.write_asset(self.stage, "Assets/Settings/Mobile_RPAsset.asset", "quarantined settings\n")
        lab.write_asset(self.stage, "Packages/manifest.json", "{}\n")
        lab.write_asset(self.stage, "ProjectSettings/ProjectVersion.txt", "version\n")
        self.dest = self.home / "snapshots"
        self.dest.mkdir()

    def test_scratch_copy_does_not_depend_on_subsequent_stage_writes(self):
        copied, content = lab.copy_scratch(self.stage, self.dest)
        self.assertEqual(lab.inventory(copied), content)
        expected = lab.checksum(copied / self.proof)
        lab.write_asset(self.stage, self.proof, "now changed\n")
        self.assertEqual(lab.checksum(copied / self.proof), expected)

    def test_copy_rejects_mutations_and_cleans_incomplete_snapshot(self):
        def mutate():
            lab.write_asset(self.stage, self.original, "changed mid-copy\n")
        with self.assertRaisesRegex(lab.SnapshotLabDenied, "mutated"):
            lab.copy_scratch(self.stage, self.dest, after_copy=mutate)
        self.assertEqual(list(self.dest.iterdir()), [])

    def test_reparse_or_symlink_rejected(self):
        path = self.stage / self.proof
        path.unlink()
        try:
            path.symlink_to(self.home / "outside")
        except (NotImplementedError, OSError):
            self.skipTest("test host does not allow symlink creation")
        with self.assertRaises(lab.SnapshotLabDenied):
            lab.copy_scratch(self.stage, self.dest)

    def test_nonregular_files_and_bounded_inventory(self):
        with self.assertRaises(lab.SnapshotLabDenied):
            lab.inventory(self.home / "missing")
        for idx in range(lab.MAX_FILES + 2):
            lab.write_asset(self.stage, f"Assets/dummy-{idx:04}.txt", "a")
        with self.assertRaisesRegex(lab.SnapshotLabDenied, "limit"):
            lab.copy_scratch(self.stage, self.dest)

    def test_main_lab_never_promotes_and_uses_only_temp_fixtures(self):
        output = lab.run_lab()
        self.assertEqual(output["status"], "scratch-copy-integrity-only")
        self.assertTrue(output["concurrentMutationDetected"])
        self.assertTrue(output["postCopySourceMutationIsolated"])
        for key in ("realStageUsed", "windowsServiceDeployed", "stageFrozen",
                    "immutableSnapshotVerified", "independentHumanAuthorization",
                    "promotionAuthorized", "nonceConsumed", "copyback"):
            self.assertFalse(output[key])


if __name__ == "__main__":
    unittest.main()
